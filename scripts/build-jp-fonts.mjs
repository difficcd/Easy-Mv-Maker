// Download the bundled Japanese faces and subset them, so the app has real Japanese type with
// the network off.
//
// The families added in #14 came from a Google Fonts @import, which works in a browser with a
// connection and nowhere else - not in the APK, and not in an installed PWA, because the service
// worker caches the app shell and not a third-party CDN. In both cases Japanese quietly fell back
// to whatever the system had.
//
// Why subset rather than bundle what Google serves: Google splits a Japanese face into ~120
// unicode-range chunks so a browser fetches only what it needs. Copying those in is 612 files and
// 16.5MB for three families - measured - which an APK carries forever. Subsetting to JIS X 0208
// level 1 is 3.6MB for the same three, and no kanji in it is lost (the characters that do drop
// out are maths and technical symbols the original faces never had).
//
// Licences: all three are SIL OFL, checked rather than assumed. Noto Sans JP reserves the name
// 'Source', not 'Noto' - it derives from Source Han Sans - so a subset may keep its family name.
// The other two reserve no name at all. The licence text ships beside the fonts in public/fonts/.
//
//   node scripts/build-jp-fonts.mjs
//
// Needs pyftsubset (fonttools) with brotli, for woff2 output.

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const RAW = 'https://raw.githubusercontent.com/google/fonts/main/ofl';
const OUT = 'src/fonts';
const LICENCES = 'public/fonts';
const WORK = 'build/fonts';

/** Regular and bold, except where one variable file covers the range. */
const FACES = [
    { family: 'Noto Sans JP', dir: 'notosansjp', file: 'NotoSansJP[wght].ttf', out: 'NotoSansJP-jis1', variable: '400 700' },
    { family: 'Shippori Mincho', dir: 'shipporimincho', file: 'ShipporiMincho-Regular.ttf', out: 'ShipporiMincho-jis1', weight: '400' },
    { family: 'Shippori Mincho', dir: 'shipporimincho', file: 'ShipporiMincho-Bold.ttf', out: 'ShipporiMincho-Bold-jis1', weight: '700' },
    { family: 'Zen Maru Gothic', dir: 'zenmarugothic', file: 'ZenMaruGothic-Regular.ttf', out: 'ZenMaruGothic-jis1', weight: '400' },
    { family: 'Zen Maru Gothic', dir: 'zenmarugothic', file: 'ZenMaruGothic-Bold.ttf', out: 'ZenMaruGothic-Bold-jis1', weight: '700' },
];

mkdirSync(WORK, { recursive: true });
mkdirSync(OUT, { recursive: true });
mkdirSync(LICENCES, { recursive: true });

async function download(url, to) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    writeFileSync(to, Buffer.from(await res.arrayBuffer()));
}

// The characters to keep, derived from the encoding rather than typed out.
execFileSync('python', ['scripts/jp-charset.py', join(WORK, 'charset.txt')], { stdio: 'inherit' });

for (const dir of [...new Set(FACES.map(f => f.dir))]) {
    await download(`${RAW}/${dir}/OFL.txt`, join(LICENCES, `OFL-${dir}.txt`));
}

const rows = [];
for (const face of FACES) {
    const src = join(WORK, face.file.replace(/[[\]]/g, '_'));
    await download(`${RAW}/${face.dir}/${encodeURIComponent(face.file)}`, src);
    const dest = join(OUT, `${face.out}.woff2`);
    execFileSync('pyftsubset', [
        src,
        `--text-file=${join(WORK, 'charset.txt')}`,
        `--output-file=${dest}`,
        '--flavor=woff2',
        '--layout-features=*',   // keep vertical forms and the kana alternates
        '--no-hinting',          // hinting is for small sizes on old screens and costs real bytes
        '--desubroutinize',
    ], { stdio: 'inherit' });
    rows.push({ ...face, dest, kb: Math.round(statSync(dest).size / 1024), from: Math.round(statSync(src).size / 1024) });
}

const css = `/* Generated by scripts/build-jp-fonts.mjs - do not edit by hand.
 *
 * Japanese faces bundled with the app rather than fetched from Google Fonts, so they are there
 * with the network off - in the APK, and in an installed PWA. Subset to JIS X 0208 level 1
 * (${readFileSync(join(WORK, 'charset.txt'), 'utf8').length} characters, no kanji lost).
 *
 * SIL Open Font License 1.1. The licence text is served beside them, in /fonts/.
 */
${rows.map(r => `@font-face {
    font-family: '${r.family}';
    font-style: normal;
    font-weight: ${r.variable || r.weight};
    font-display: swap;
    src: url('./${r.out}.woff2') format('woff2');
}`).join('\n')}
`;
writeFileSync(join(OUT, 'japanese.css'), css);

const total = rows.reduce((n, r) => n + r.kb, 0);
for (const r of rows) console.log(`  ${r.out.padEnd(26)} ${String(r.from).padStart(5)} KB -> ${String(r.kb).padStart(4)} KB`);
console.log(`  ${'total'.padEnd(26)} ${' '.repeat(5)}    ${String(total).padStart(4)} KB`);
